    ('H0', f"{H0_kms:.3f}", "67.4-73.0", "—"),
    ('r_d', f"{r_d:.2f}", "147.09", f"{(r_d/147.09-1)*100:+.3f}%"),
    ('θ_*', f"{theta_star:.6f}", "0.010409", f"{(theta_star/0.010409-1)*100:+.3f}%"),
    ('ℓ_A', f"{ell_A:.2f}", "301.8", f"{(ell_A/301.8-1)*100:+.3f}%"),
    ('R_shift', f"{R_shift:.4f}", "1.7502", f"{(R_shift/1.7502-1)*100:+.3f}%"),
    ('t_0', f"{t0_Gyr:.3f}", "13.787", f"{(t0_Gyr/13.787-1)*100:+.3f}%"),
    ('q_0', f"{q0:.4f}", "-0.527", f"{(q0/(-0.527)-1)*100:+.3f}%"),
    ('z_eq', f"{z_eq:.1f}", "3402", f"{(z_eq/3402-1)*100:+.2f}%"),
    ('η', f"{eta:.4e}", "6.1e-10", f"{(eta/6.1e-10-1)*100:+.2f}%"),
    ('Y_p', f"{Y_p:.4f}", "0.2449", f"{(Y_p/0.2449-1)*100:+.2f}%"),
    ('D/H', f"{D_H:.4e}", "2.55e-5", f"{(D_H/2.55e-5-1)*100:+.2f}%"),
    ('σ_8', f"{sigma8_nea:.4f}", "0.811", f"{(sigma8_nea/0.811-1)*100:+.2f}%"),
    ('S_8', f"{S8:.4f}", "0.832", f"{(S8/0.832-1)*100:+.2f}%"),
    ('Γ', f"{Gamma:.4f}", "0.20", f"{(Gamma/0.20-1)*100:+.2f}%"),
